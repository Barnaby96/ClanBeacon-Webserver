"""Export normalised OSRS drop groups into a Python data module."""

from argparse import ArgumentParser
from pathlib import Path
from pprint import pformat

from utils.osrs_drop_database_excel import load_drop_database_xlsx


GENERATED_HEADER = """\"\"\"Generated OSRS drop group data.

Do not edit this file manually. Regenerate it from the maintained drop
database workbook.
\"\"\""""


def build_drop_group_data_records(database):
    return tuple(
        {
            "drop_group_id": group.group_id,
            "display_name": group.group_name,
            "source_ids": group.source_ids,
            "source_names": group.source_names,
            "drop_ids": group.drop_ids,
            "drop_names": group.drop_names,
            "drop_rates": group.drop_rates,
            "drop_counting_modes": group.drop_counting_modes,
            "drop_quantities": group.drop_quantities,
            "access_notes": group.access_notes,
            "notes": group.notes,
            "include_pet": group.include_pet,
        }
        for group in sorted(
            database.groups,
            key=lambda group: group.group_id,
        )
    )


def build_drop_row_data_records(database):
    """Preserve all imported rows, regardless of unique-group inclusion."""
    return tuple(
        {
            "source_ids": row.source_ids,
            "source_names": row.source_names,
            "group_ids": row.group_ids,
            "group_names": row.group_names,
            "drop_id": row.drop_id,
            "drop_name": row.drop_name,
            "drop_rates": row.drop_rates,
            "drop_counting_mode": row.drop_counting_mode,
            "drop_quantity": row.drop_quantity,
            "include_in_unique_group": row.include_in_unique_group,
            "include_pet": row.include_pet,
            "access_notes": row.access_notes,
            "notes": row.notes,
        }
        for row in database.rows
    )


def format_drop_group_data_module(database):
    group_records = build_drop_group_data_records(
        database
    )
    drop_rows = build_drop_row_data_records(
        database
    )

    return (
        GENERATED_HEADER
        + "\n\n"
        + "DROP_GROUP_DATA = "
        + pformat(
            group_records,
            sort_dicts=False,
            width=88,
        )
        + "\n\n"
        + "DROP_ROW_DATA = "
        + pformat(
            drop_rows,
            sort_dicts=False,
            width=88,
        )
        + "\n"
    )


def write_drop_group_data_module(database, output_path):
    output_path = Path(
        output_path
    )

    output_path.write_text(
        format_drop_group_data_module(
            database
        ),
        encoding="utf-8",
    )

    return output_path


def build_argument_parser():
    parser = ArgumentParser(
        description="Export OSRS drop group data from the drop database workbook.",
    )
    parser.add_argument(
        "workbook_path",
        help="Path to the maintained drop database .xlsx file.",
    )
    parser.add_argument(
        "--sheet-name",
        default=None,
        help="Optional worksheet name. Defaults to the first worksheet.",
    )
    parser.add_argument(
        "--output",
        default="utils/osrs_drop_group_data.py",
        help="Output Python data module path.",
    )

    return parser


def main(argv=None):
    parser = build_argument_parser()
    args = parser.parse_args(
        argv
    )

    database = load_drop_database_xlsx(
        args.workbook_path,
        sheet_name=args.sheet_name,
    )
    output_path = write_drop_group_data_module(
        database,
        args.output,
    )

    print(
        f"Wrote {len(database.groups)} drop groups to {output_path}"
    )


if __name__ == "__main__":
    main()
